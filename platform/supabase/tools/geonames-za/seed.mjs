// Turns places.csv + aliases.csv into chunked, re-runnable seed SQL (phase P2).
// Pure function seedChunks() plus a small CLI:
//   node seed.mjs [--in out] [--out out/seed] [--chunks 7]
import { PROVINCES } from "./lib.mjs";

const PROVINCE_NAME = Object.fromEntries(Object.values(PROVINCES).map((p) => [p.code, p.name]));
const lit = (v) => (v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => {
  const n = Number(v);
  if (!Number.isFinite(n)) throw new Error(`not a number: ${v}`);
  return String(n);
};
const pad = (n) => String(n).padStart(2, "0");

/**
 * Most-populous place for each name key and each old-name key: the only safe target when an
 * older hand-added city row (no GeoNames id yet) has the same name.
 */
function adoptionKeys(places, aliases) {
  const byKey = new Map();
  const consider = (key, p) => {
    const cur = byKey.get(key);
    if (!cur || Number(p.population) > Number(cur.population)) byKey.set(key, p);
  };
  const byId = new Map(places.map((p) => [String(p.geonames_id), p]));
  for (const p of places) consider(p.name_key, p);
  for (const a of aliases) if (a.kind === "old_name" && byId.has(String(a.geonames_id))) consider(a.alias_key, byId.get(String(a.geonames_id)));
  const out = new Map();
  for (const [key, p] of byKey) {
    const id = String(p.geonames_id);
    if (!out.has(id)) out.set(id, []);
    out.get(id).push(key);
  }
  return out;
}

export function seedChunks(places, aliases, { chunks = 7, sourceNote = "" } = {}) {
  const sorted = [...places].sort((a, b) => Number(b.population) - Number(a.population) || Number(a.geonames_id) - Number(b.geonames_id));
  const total = sorted.length;
  const size = Math.ceil(total / chunks);
  const adopt = adoptionKeys(places, aliases);
  const aliasesById = new Map();
  for (const a of aliases) {
    const id = String(a.geonames_id);
    if (!aliasesById.has(id)) aliasesById.set(id, []);
    aliasesById.get(id).push(a);
  }
  const files = [];
  for (let c = 0; c < chunks; c++) {
    const part = sorted.slice(c * size, (c + 1) * size);
    if (!part.length) break;
    const no = pad(c + 1), of = pad(chunks);
    const label = `SA places seed ${no} of ${of}`;
    const partAliases = part.flatMap((p) => aliasesById.get(String(p.geonames_id)) || []);
    const adoptRows = part.flatMap((p) => (adopt.get(String(p.geonames_id)) || []).map((k) => [p.geonames_id, k]));
    for (const p of part) if (!PROVINCE_NAME[p.province_code]) throw new Error(`unknown province ${p.province_code} for ${p.geonames_id}`);
    const placeValues = part
      .map((p) => `  (${num(p.geonames_id)}, ${lit(p.name)}, ${lit(p.province_code)}, ${lit(p.place_type)}, ${lit(p.feature_code)}, ${num(p.population || 0)}, ${num(p.lat)}, ${num(p.lng)}, ${lit(p.near_label)})`)
      .join(",\n");
    const aliasValues = partAliases.map((a) => `  (${num(a.geonames_id)}, ${lit(a.alias)}, ${lit(a.kind)})`).join(",\n");
    const adoptValues = adoptRows.map(([id, k]) => `  (${num(id)}, ${lit(k)})`).join(",\n");
    const sql = `-- ${label}: South African cities, towns and villages (phase P2).
-- Place names © GeoNames (geonames.org), CC BY 4.0. ${sourceNote}
-- Generated by platform/supabase/tools/geonames-za/seed.mjs. Do not edit by hand; regenerate.
--
-- Run after the SA places schema (20261123030000_sa_places_schema.sql). Chunks can run in any
-- order and are safe to re-run: rows are matched by GeoNames id. A city row added by hand with
-- the same name or old name (and no GeoNames id yet) is linked instead of duplicated: it keeps
-- its id, so watches stay attached, and takes the official name.
-- Hidden cities stay hidden; hand-made (source = 'manual') rows are never overwritten.
-- This chunk: ${part.length} places (population ${Number(part[0].population).toLocaleString("en-ZA")} down to ${Number(part[part.length - 1].population).toLocaleString("en-ZA")}), ${partAliases.length} aliases. All chunks: ${total} places.

DO $precheck$
DECLARE
  missing text[] := ARRAY[]::text[];
  r record;
BEGIN
  FOR r IN SELECT * FROM (VALUES
      ('cities', 'geonames_id'), ('cities', 'name_key'), ('cities', 'province_code'), ('cities', 'place_type'),
      ('cities', 'feature_code'), ('cities', 'population'), ('cities', 'near_label'), ('cities', 'status'),
      ('cities', 'source'), ('cities', 'province'), ('cities', 'country'), ('cities', 'center_lat'), ('cities', 'center_lng'),
      ('city_aliases', 'alias_key'), ('city_aliases', 'kind')) AS t(tbl, col) LOOP
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = r.tbl AND column_name = r.col) THEN
      missing := missing || (r.tbl || '.' || r.col || ' column');
    END IF;
  END LOOP;
  IF to_regclass('public.cities_geonames_id_uidx') IS NULL THEN
    missing := missing || 'cities_geonames_id_uidx index'::text;
  END IF;
  IF to_regclass('public.provinces') IS NULL THEN
    missing := missing || 'provinces table'::text;
  ELSIF (SELECT count(*) FROM public.provinces WHERE country_iso2 = 'ZA') < 9 THEN
    missing := missing || 'the 9 provinces'::text;
  END IF;
  IF to_regprocedure('public.place_name_key(text)') IS NULL THEN
    missing := missing || 'place_name_key(text) function'::text;
  END IF;
  IF array_length(missing, 1) > 0 THEN
    RAISE EXCEPTION '${label}: not applied, missing %. Run the SA places schema first. Nothing was changed.',
      array_to_string(missing, ', ');
  END IF;
END
$precheck$;

-- Staging tables live only in this session; the load below is one statement, so it applies fully or not at all.
DROP TABLE IF EXISTS pg_temp.sa_seed_places, pg_temp.sa_seed_aliases, pg_temp.sa_seed_adopt;
CREATE TEMP TABLE sa_seed_places (
  geonames_id bigint PRIMARY KEY, name text NOT NULL, province_code text NOT NULL, place_type text NOT NULL,
  feature_code text NOT NULL, population integer NOT NULL, lat double precision NOT NULL,
  lng double precision NOT NULL, near_label text
);
CREATE TEMP TABLE sa_seed_aliases (geonames_id bigint NOT NULL, alias text NOT NULL, kind text NOT NULL);
CREATE TEMP TABLE sa_seed_adopt (geonames_id bigint NOT NULL, name_key text NOT NULL);

INSERT INTO sa_seed_places (geonames_id, name, province_code, place_type, feature_code, population, lat, lng, near_label) VALUES
${placeValues};
${partAliases.length ? `
INSERT INTO sa_seed_aliases (geonames_id, alias, kind) VALUES
${aliasValues};
` : ""}${adoptRows.length ? `
INSERT INTO sa_seed_adopt (geonames_id, name_key) VALUES
${adoptValues};
` : ""}
DO $load$
DECLARE
  v_linked int := 0;
  v_new int := 0;
  v_updated int := 0;
  v_aliases int := 0;
  v_names text;
  v_missing int;
  v_alias_missing int;
  v_loaded int;
BEGIN
  -- 1. Link hand-added rows that carry the same name (or an old name) and no GeoNames id yet.
  --    Only when exactly one such row exists for that name, and the place is not linked already.
  WITH cand AS (
    SELECT c.id, a.geonames_id, count(*) OVER (PARTITION BY a.name_key) AS n_rows
    FROM sa_seed_adopt a
    JOIN public.cities c ON c.geonames_id IS NULL AND c.name_key = a.name_key
    WHERE NOT EXISTS (SELECT 1 FROM public.cities x WHERE x.geonames_id = a.geonames_id)
  ), pick AS (
    SELECT DISTINCT ON (geonames_id) id, geonames_id FROM cand WHERE n_rows = 1 ORDER BY geonames_id, id
  ), linked AS (
    UPDATE public.cities c SET geonames_id = p.geonames_id, source = 'geonames'
    FROM pick p
    WHERE c.id = p.id
      AND NOT EXISTS (SELECT 1 FROM pick q WHERE q.id = p.id AND q.geonames_id <> p.geonames_id)
    RETURNING c.name
  )
  SELECT count(*), string_agg(name, ', ' ORDER BY name) INTO v_linked, v_names FROM linked;
  IF v_linked > 0 THEN
    RAISE NOTICE 'Heads-up: linked % existing city row(s) to GeoNames instead of adding duplicates: %', v_linked, v_names;
  END IF;

  -- 2. Refresh GeoNames rows that differ; never touch hand-made rows, status or an existing centre.
  WITH upd AS (
    UPDATE public.cities c SET
      name = s.name,
      province_code = s.province_code,
      province = pr.name,
      country = 'South Africa',
      country_iso2 = 'ZA',
      place_type = s.place_type,
      feature_code = s.feature_code,
      population = s.population,
      near_label = s.near_label,
      center_lat = coalesce(c.center_lat, s.lat),
      center_lng = coalesce(c.center_lng, s.lng)
    FROM sa_seed_places s
    JOIN public.provinces pr ON pr.code = s.province_code
    WHERE c.geonames_id = s.geonames_id
      AND c.source = 'geonames'
      AND (c.name, c.province_code, c.province, c.country, c.place_type, c.feature_code, c.population, c.near_label,
           c.center_lat IS NULL, c.center_lng IS NULL)
          IS DISTINCT FROM
          (s.name, s.province_code, pr.name, 'South Africa'::text, s.place_type, s.feature_code, s.population, s.near_label,
           false, false)
    RETURNING 1
  )
  SELECT count(*) INTO v_updated FROM upd;

  -- 3. Add the rest.
  WITH ins AS (
    INSERT INTO public.cities (name, province, country, country_iso2, province_code, geonames_id, place_type,
                               feature_code, population, near_label, center_lat, center_lng, source, status)
    SELECT s.name, pr.name, 'South Africa', 'ZA', s.province_code, s.geonames_id, s.place_type,
           s.feature_code, s.population, s.near_label, s.lat, s.lng, 'geonames', 'active'
    FROM sa_seed_places s
    JOIN public.provinces pr ON pr.code = s.province_code
    WHERE NOT EXISTS (SELECT 1 FROM public.cities c WHERE c.geonames_id = s.geonames_id)
    ON CONFLICT (geonames_id) WHERE geonames_id IS NOT NULL DO NOTHING
    RETURNING 1
  )
  SELECT count(*) INTO v_new FROM ins;

  -- 4. Aliases (old names and alternate spellings) for search.
  WITH ins AS (
    INSERT INTO public.city_aliases (city_id, alias, kind)
    SELECT c.id, a.alias, a.kind
    FROM sa_seed_aliases a
    JOIN public.cities c ON c.geonames_id = a.geonames_id
    ON CONFLICT (city_id, alias_key) DO NOTHING
    RETURNING 1
  )
  SELECT count(*) INTO v_aliases FROM ins;

  -- 5. Check this chunk before finishing (an error here undoes steps 1-4).
  SELECT count(*) INTO v_missing
  FROM sa_seed_places s WHERE NOT EXISTS (SELECT 1 FROM public.cities c WHERE c.geonames_id = s.geonames_id);
  SELECT count(*) INTO v_alias_missing
  FROM sa_seed_aliases a
  JOIN public.cities c ON c.geonames_id = a.geonames_id
  WHERE NOT EXISTS (SELECT 1 FROM public.city_aliases x WHERE x.city_id = c.id AND x.alias_key = public.place_name_key(a.alias));
  IF v_missing > 0 OR v_alias_missing > 0 THEN
    RAISE EXCEPTION '${label}: not applied, % places and % aliases did not load. Nothing was changed.', v_missing, v_alias_missing;
  END IF;
  SELECT count(*) INTO v_loaded FROM public.cities WHERE geonames_id IS NOT NULL;
  SELECT count(*), string_agg(name, ', ' ORDER BY name) INTO v_linked, v_names
  FROM (SELECT name FROM public.cities WHERE geonames_id IS NULL ORDER BY name LIMIT 20) u;
  IF v_linked > 0 THEN
    RAISE NOTICE 'Heads-up: city rows without a GeoNames id (added by hand, kept as they are): %', v_names;
  END IF;
  IF v_loaded >= ${total} THEN
    RAISE NOTICE 'SA places seed: all ${chunks} chunks loaded (% places with a GeoNames id).', v_loaded;
  ELSE
    RAISE NOTICE 'SA places seed: % of ${total} places loaded so far; run the remaining chunks.', v_loaded;
  END IF;
  RAISE NOTICE '${label}: % added, % updated, % aliases added.', v_new, v_updated, v_aliases;
  RAISE NOTICE '${label}: OK';
END
$load$;

DROP TABLE IF EXISTS pg_temp.sa_seed_places, pg_temp.sa_seed_aliases, pg_temp.sa_seed_adopt;
`;
    files.push({ name: `sa-places-seed-${no}.sql`, sql, places: part.length, aliases: partAliases.length });
  }
  return files;
}

// CLI
import { fileURLToPath } from "node:url";
if (process.argv[1] && fileURLToPath(import.meta.url) === (await import("node:path")).resolve(process.argv[1])) {
  const fs = await import("node:fs");
  const path = await import("node:path");
  const { parseCsv } = await import("./lib.mjs");
  const here = path.dirname(fileURLToPath(import.meta.url));
  const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? process.argv[i + 1] : d; };
  const inDir = path.resolve(arg("in", path.join(here, "out")));
  const outDir = path.resolve(arg("out", path.join(inDir, "seed")));
  const places = parseCsv(fs.readFileSync(path.join(inDir, "places.csv"), "utf8"));
  const aliases = parseCsv(fs.readFileSync(path.join(inDir, "aliases.csv"), "utf8"));
  let note = "";
  try { note = `GeoNames file of ${JSON.parse(fs.readFileSync(path.join(inDir, "meta.json"), "utf8")).source_file_modified.slice(0, 10)}.`; } catch {}
  const files = seedChunks(places, aliases, { chunks: Number(arg("chunks", 7)), sourceNote: note });
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of files) {
    fs.writeFileSync(path.join(outDir, f.name), f.sql);
    console.log(`${f.name}: ${f.places} places, ${f.aliases} aliases, ${(f.sql.length / 1024).toFixed(0)} KB`);
  }
}
