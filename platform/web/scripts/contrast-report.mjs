import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const cssPath = path.resolve(here, "../src/index.css");
const outPath = path.resolve(here, "../../docs/CONTRAST_REPORT.md");

function hexToRgb(hex) {
  let h = hex.replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  const n = Number.parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function channel(c) {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

function luminance(hex) {
  const [r, g, b] = hexToRgb(hex);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

function contrast(a, b) {
  const L1 = luminance(a);
  const L2 = luminance(b);
  const lighter = Math.max(L1, L2);
  const darker = Math.min(L1, L2);
  return (lighter + 0.05) / (darker + 0.05);
}

function extractBlock(css, selector) {
  const re = new RegExp(`${selector.replace(".", "\\.")}\\s*\\{([\\s\\S]*?)\\n\\}`);
  const match = css.match(re);
  if (!match) throw new Error(`Could not find ${selector} in index.css`);
  const vars = {};
  for (const line of match[1].split("\n")) {
    const found = line.match(/(--[\w-]+)\s*:\s*([^;]+);/);
    if (!found) continue;
    const value = found[2].trim();
    if (value.startsWith("#")) vars[found[1]] = value;
  }
  return vars;
}

const css = fs.readFileSync(cssPath, "utf8");
const light = extractBlock(css, ":root");
const darkOverrides = extractBlock(css, ".dark");
const dark = { ...light, ...darkOverrides };

const pairs = [
  ["Primary button text", "--color-on-primary", "--color-primary-700", 4.5],
  ["Primary button edge on page", "--color-primary-edge", "--color-bg-page", 3],
  ["Primary button edge on card", "--color-primary-edge", "--color-bg-card", 3],
  ["Brand accent on card (UI)", "--color-primary-600", "--color-bg-card", 3],
  ["Link on card", "--color-text-link", "--color-bg-card", 4.5],
  ["Link on page", "--color-text-link", "--color-bg-page", 4.5],
  ["Body text on card", "--color-text-primary", "--color-bg-card", 4.5],
  ["Secondary text on card", "--color-text-secondary", "--color-bg-card", 4.5],
  ["Helper text on card", "--color-text-tertiary", "--color-bg-card", 4.5],
  ["Helper text on page", "--color-text-tertiary", "--color-bg-page", 4.5],
  ["Success button text", "--color-on-success", "--color-success", 4.5],
  ["Warning button text", "--color-on-warning", "--color-warning", 4.5],
  ["Danger button text", "--color-on-danger", "--color-danger", 4.5],
  ["Info button text", "--color-on-info", "--color-info", 4.5],
  ["Success badge", "--color-success-text", "--color-success-light", 4.5],
  ["Warning badge", "--color-warning-text", "--color-warning-light", 4.5],
  ["Danger badge", "--color-danger-text", "--color-danger-light", 4.5],
  ["Info badge", "--color-info-text", "--color-info-light", 4.5],
  ["Focus ring on card", "--color-focus", "--color-bg-card", 3],
];

const rows = [];
let failed = 0;
for (const themeName of ["light", "dark"]) {
  const tokens = themeName === "light" ? light : dark;
  for (const [label, fgName, bgName, minimum] of pairs) {
    const fg = tokens[fgName];
    const bg = tokens[bgName];
    if (!fg || !bg) {
      rows.push({ themeName, label, fgName, bgName, fg: fg || "missing", bg: bg || "missing", ratio: 0, minimum, pass: false });
      failed += 1;
      continue;
    }
    const ratio = contrast(fg, bg);
    const pass = ratio + 0.005 >= minimum;
    if (!pass) failed += 1;
    rows.push({ themeName, label, fgName, bgName, fg, bg, ratio, minimum, pass });
  }
}

const lines = [
  "# Contrast report",
  "",
  "Generated by `platform/web/scripts/contrast-report.mjs` from the hex tokens in `platform/web/src/index.css`.",
  "WCAG 2.1 AA: 4.5:1 for text, 3:1 for UI chrome (buttons against the page, focus ring, brand accent).",
  "",
  "Brand teal `#0d9488` (`--color-primary-600`) stays the accent colour. It does not pass 4.5:1 as small text on white, so buttons and links use `--color-primary-700` (`#0f766e`).",
  "",
  "| Theme | Pair | Foreground | Background | Ratio | Minimum | Result |",
  "| --- | --- | --- | --- | ---: | ---: | --- |",
];

for (const row of rows) {
  lines.push(
    `| ${row.themeName} | ${row.label} | \`${row.fg}\` | \`${row.bg}\` | ${row.ratio.toFixed(2)} | ${row.minimum.toFixed(1)} | ${row.pass ? "pass" : "fail"} |`
  );
}

lines.push("", failed === 0 ? "All checked pairs pass." : `${failed} pair(s) failed.`, "");
fs.writeFileSync(outPath, lines.join("\n"));
console.log(lines.join("\n"));
if (failed) process.exit(1);
